/**
 * THE APPLIED SET IS DERIVED, NOT HAND-PICKED, AND THAT IS THE WHOLE POINT.
 *
 * `frameless-angular-v1` T002 ruling 4 modelled this gate on the Svelte one,
 * which consumes `eslint-plugin-svelte`'s `configs.recommended` - a
 * THIRD-PARTY-AUTHORED applied set, which is what makes an arbiter genuinely
 * independent: WE did not choose which rules judge us. T003 then REFUTED THAT
 * RULING'S PREMISE by measurement: `@angular-eslint/eslint-plugin` exports only
 * `rules` (50) and `@angular-eslint/eslint-plugin-template` only `processors` and
 * `rules` (41). NEITHER PUBLISHES A CONFIG. The presets live solely in the
 * `angular-eslint` META package, which T002's own stop_if forbids for a
 * measured reason - see `WHY_THE_META_PACKAGE_IS_NOT_USED`.
 *
 * T003a's answer, and the reason the conclusion survives STRONGER than the
 * premise: every `@angular-eslint` rule carries its OWN membership flag,
 * `meta.docs.recommended === 'recommended'`, and the meta package's published
 * preset is GENERATED FROM THAT SAME METADATA - its header reads, verbatim,
 * "DO NOT EDIT THIS FILE / In order to update this config, please run
 * `pnpm update-rule-configs`". So deriving here is not transcription and not
 * reconstruction: it is running UPSTREAM'S OWN GENERATOR against UPSTREAM'S OWN
 * SOURCE OF TRUTH, already sitting inside the two permitted leaf packages. A rule
 * upstream adds to `recommended` arrives here automatically, which is exactly the
 * property a transcribed set would fake.
 */
function recommendedRules(prefix: string, rules: Readonly<Record<string, unknown>>): string[] {
	return Object.entries(rules)
		.filter(
			([, rule]) =>
				(rule as { meta?: { docs?: { recommended?: unknown } } }).meta?.docs?.recommended ===
				'recommended',
		)
		.map(([name]) => `${prefix}${name}`)
		.sort();
}

