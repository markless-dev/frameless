/**
 * THE MEASURED WHITESPACE POLICY (T003 measurement M1), stated as a property of
 * the RESULT rather than of the layout that produced it.
 *
 * `parseTemplate` applies Angular's `preserveWhitespaces: false` default, so the
 * nodes read here are already condensed - MEASURED at 22.0.8, which is what makes
 * this readable straight off Angular's own tree instead of reimplementing the
 * rule. Condense drops a whitespace-ONLY text node outright and collapses a run of
 * two or more whitespace characters inside a content-bearing node to a single
 * space, but a LONE newline survives verbatim.
 *
 * All the failures land in one observable, so one check catches them all: AFTER
 * CONDENSE, NO EMITTED TEXT MAY CARRY AN UNTRIMMED EDGE - plain text or an
 * interpolation's literal segments.
 *
 *   `<button>\n\tincrement\n</button>` -> Text `" increment\n"`   rejected
 *   `<p>{{ a }}\n/{{ b }}</p>`         -> BoundText `["","\n/",""]` rejected, and
 *                                         this is S2's `1/2` becoming `1\n/2`
 *   the shipped layout                 -> the whitespace node is gone  accepted
 *
 * BoundText is read through `ast.strings`, which is where the LITERAL segments of
 * an interpolation live; the empty leading and trailing segments of
 * `{{ a }}/{{ b }}` are normal and are skipped, so this is not "reject any
 * interpolation".
 */
function whitespaceViolations(file: string, parsed: Parsed): GateViolation[] {
	const violations: GateViolation[] = [];
	walkTemplate(parsed.templateNodes, (node) => {
		const name = templateNodeName(node);
		const line = lineOfTemplate(parsed, node);
		if (name === 'Text') {
			const content = String(node.value ?? '');
			if (content !== content.trim() || content.length === 0)
				violations.push(
					violation(
						file,
						'whitespace-stable-text',
						`Emitted Angular template has the condensed text node ${JSON.stringify(content)}, which carries an untrimmed edge. Angular's preserveWhitespaces:false default condenses a run of whitespace to a single space and keeps a lone newline verbatim, so this text would render differently from the react, solid, qwik, svelte and vue lanes`,
						line,
					),
				);
			return;
		}
		if (name !== 'BoundText') return;
		for (const segment of (node.value?.ast?.strings ?? []) as string[]) {
			if (segment.length === 0 || segment === segment.trim()) continue;
			violations.push(
				violation(
					file,
					'whitespace-stable-text',
					`Emitted Angular template has the interpolation text segment ${JSON.stringify(segment)}, which carries an untrimmed edge and would render differently from the react, solid, qwik, svelte and vue lanes`,
					line,
				),
			);
		}
	});
	return violations;
}

