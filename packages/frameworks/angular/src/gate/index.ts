/** Depth-first walk over a TypeScript-ESLint AST, never following back-references. */
function walkTs(value: unknown, visit: (record: Node) => void): void {
	if (!value || typeof value !== 'object') return;
	if (Array.isArray(value)) {
		value.forEach((entry) => walkTs(entry, visit));
		return;
	}
	const record = value as Node;
	if (typeof record.type !== 'string') return;
	visit(record);
	for (const [key, child] of Object.entries(record)) {
		if (key === 'parent' || key === 'loc' || key === 'range') continue;
		walkTs(child, visit);
	}
}

/**
 * Angular's template AST nodes are CLASS INSTANCES with heterogeneous child
 * fields, so the walk follows an explicit key list rather than every own
 * property - `sourceSpan`, `keySpan` and `value` are span objects and parsed
 * expressions, not template nodes, and descending into them would report an
 * `AST` node kind for every binding.
 */
const TEMPLATE_CHILD_KEYS = [
	'children',
	'branches',
	'attributes',
	'inputs',
	'outputs',
	'references',
	'variables',
	'templateAttrs',
	'directives',
	'cases',
	'contents',
	'empty',
	'item',
] as const;

function walkTemplate(nodes: unknown, visit: (node: Node) => void): void {
	const seen = new Set<unknown>();
	const step = (value: unknown): void => {
		if (!value || typeof value !== 'object') return;
		if (Array.isArray(value)) {
			value.forEach(step);
			return;
		}
		if (seen.has(value)) return;
		seen.add(value);
		const node = value as Node;
		visit(node);
		for (const key of TEMPLATE_CHILD_KEYS) step(node[key]);
	};
	step(nodes);
}

