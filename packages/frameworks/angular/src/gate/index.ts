/**
 * The lane's version floor, DERIVED as the max over the inventory rather than
 * written down twice. Emitted output is claimed safe at this Angular version and
 * NOT below it, which is a narrower and more honest claim than the Vue lane's
 * "safe across the whole major line" - see the inventory's doc comment.
 */
export const ANGULAR_BASELINE_FLOOR: string = BASELINE_FORM_INVENTORY.map(
	(entry) => entry.floor,
).reduce((highest, floor) => {
	const [left, right] = [highest.split('.').map(Number), floor.split('.').map(Number)];
	return (right[0]! - left[0]! || right[1]! - left[1]!) > 0 ? floor : highest;
}, '0.0');

export type ObservedForm = {
	readonly kind: BaselineFormKind;
	readonly form: string;
	readonly line: number | null;
};

function bindingTypeName(type: unknown): string {
	const name = (BindingType as unknown as Record<number, string>)[type as number];
	return typeof name === 'string' ? name : `TYPE_${String(type)}`;
}

function templateNodeName(node: Node): string {
	return node?.constructor?.name ?? 'UNKNOWN';
}

function observeForms(parsed: Parsed): ObservedForm[] {
	const found: ObservedForm[] = [];
	walkTs(parsed.module, (node) => {
		if (node.type === 'ImportDeclaration') {
			const from = String((node.source as Node | undefined)?.value ?? '?');
			const specifiers = (node.specifiers ?? []) as Node[];
			const line = lineOfTs(node);
			if (specifiers.length === 0) found.push({ kind: 'import', form: `${from}#*`, line });
			for (const specifier of specifiers)
				found.push({
					kind: 'import',
					form: `${from}#${
						specifier.type === 'ImportSpecifier'
							? String(specifier.imported?.name ?? '?')
							: specifier.type === 'ImportDefaultSpecifier'
								? 'default'
								: '*'
					}`,
					line,
				});
		}
		if (node.type === 'Decorator')
			found.push({
				kind: 'decorator',
				form: String(node.expression?.callee?.name ?? node.expression?.name ?? '?'),
				line: lineOfTs(node),
			});
	});
	for (const property of (parsed.metadata?.properties ?? []) as Node[])
		found.push({
			kind: 'component-metadata',
			form: String(property.key?.name ?? property.key?.value ?? '?'),
			line: lineOfTs(property),
		});
	if (parsed.metadata)
		found.push({ kind: 'component-metadata', form: '(no standalone key)', line: null });
	for (const clause of (parsed.component?.implements ?? []) as Node[])
		found.push({ kind: 'class-heritage', form: 'implements', line: lineOfTs(clause) });
	if (parsed.component?.superClass)
		found.push({ kind: 'class-heritage', form: 'extends', line: lineOfTs(parsed.component) });
	for (const member of (parsed.component?.body?.body ?? []) as Node[]) {
		const line = lineOfTs(member);
		if (member.type === 'PropertyDefinition')
			found.push({ kind: 'class-member', form: member.static ? 'static-property' : 'property', line });
		else if (member.type === 'MethodDefinition')
			found.push({
				kind: 'class-member',
				form: member.kind === 'method' ? 'method' : String(member.kind),
				line,
			});
		else found.push({ kind: 'class-member', form: String(member.type), line });
	}

	walkTemplate(parsed.templateNodes, (node) => {
		const name = templateNodeName(node);
		const line = lineOfTemplate(parsed, node);
		found.push({ kind: 'template-node', form: name, line });
		if (name === 'BoundText') found.push({ kind: 'template-binding', form: 'interpolation', line });
		if (name === 'BoundAttribute')
			found.push({ kind: 'template-binding', form: bindingTypeName(node.type), line });
		if (name === 'BoundEvent') found.push({ kind: 'template-binding', form: 'event', line });
		if (name === 'IfBlock') found.push({ kind: 'control-flow', form: '@if', line });
		if (name === 'IfBlockBranch' && node.expression === null)
			found.push({ kind: 'control-flow', form: '@else', line });
		if (name === 'ForLoopBlock') {
			found.push({ kind: 'control-flow', form: '@for', line });
			if (node.empty) found.push({ kind: 'control-flow', form: '@empty', line });
		}
	});
	return found;
}

/**
 * Every form the emitted source actually contains, deduped and sorted. Exported
 * because a fail-closed allowlist that observes NOTHING passes vacuously, and
 * `test/gate.test.ts` pins the observed set of the shipped corpus against a
 * literal - so a walk that stopped descending is a red test rather than a silently
 * green gate.
 */
export function collectEmittedForms(source: string): ReadonlyArray<{
	readonly kind: BaselineFormKind;
	readonly form: string;
}> {
	const parsed = parseEmitted('generated/inline.ts', source);
	if (!parsed) throw new Error('collectEmittedForms received a source TypeScript could not parse');
	const seen = new Set<string>();
	const forms: Array<{ kind: BaselineFormKind; form: string }> = [];
	for (const observation of observeForms(parsed)) {
		const key = `${observation.kind}:${observation.form}`;
		if (seen.has(key)) continue;
		seen.add(key);
		forms.push({ kind: observation.kind, form: observation.form });
	}
	return forms.sort((left, right) =>
		`${left.kind}:${left.form}`.localeCompare(`${right.kind}:${right.form}`),
	);
}

function inventoryViolations(file: string, parsed: Parsed): GateViolation[] {
	const violations: GateViolation[] = [];
	const reported = new Set<string>();
	for (const observation of observeForms(parsed)) {
		const key = `${observation.kind}:${observation.form}`;
		if (INVENTORY.has(key) || reported.has(key)) continue;
		reported.add(key);
		violations.push(
			violation(
				file,
				'baseline-form-inventory',
				`Emitted Angular source uses the ${observation.kind} form ${JSON.stringify(observation.form)}, which is not in the baseline form inventory. IR-4 is DEFERRED, so this emitter's only discharge of the version corollary's second conjunct is an explicit allowlist with a recorded floor per entry; a new form has to be added to BASELINE_FORM_INVENTORY with a version floor and an honest floor-evidence status, and it may raise ANGULAR_BASELINE_FLOOR`,
				observation.line,
			),
		);
	}
	return violations;
}

